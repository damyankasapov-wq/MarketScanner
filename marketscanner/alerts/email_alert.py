"""
Email alert for an Opening Range Breakout trade proposal.

Subject:  [MarketScanner] SPY ORB BUY @ 583.90 · TP 585.85 · SL 581.95
Body:     header band, proposal table (identical content in plain text and
          HTML), inline chart, footer. Informational only — nothing trades.
"""
import io
import logging
import smtplib
from datetime import date, datetime
from email.mime.image import MIMEImage
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from typing import Optional

import pytz

from marketscanner import config
from marketscanner.strategies.base import Signal
from marketscanner.strategies.orb_session import OrbSnapshot

log = logging.getLogger(__name__)

_ET = pytz.timezone(config.TIMEZONE)

_SIDE_COLOUR = {"BUY": "#16a34a", "SELL": "#dc2626"}
_SIDE_ARROW = {"BUY": "▲", "SELL": "▼"}


def _side(signal: Signal) -> str:
    return signal.side or ("BUY" if signal.direction == "UP" else "SELL")


def _entry(signal: Signal) -> float:
    return signal.entry if signal.entry is not None else signal.price


def _fmt(x: Optional[float]) -> str:
    return "—" if x is None else f"{x:.2f}"


def _et(ts: Optional[datetime], fmt: str) -> str:
    return "—" if ts is None else ts.astimezone(_ET).strftime(fmt)


def build_subject(signal: Signal) -> str:
    return (
        f"[MarketScanner] {signal.market} ORB {_side(signal)} @ {_fmt(_entry(signal))}"
        f" · TP {_fmt(signal.take_profit)} · SL {_fmt(signal.stop_loss)}"
    )


def build_rows(signal: Signal, snapshot: Optional[OrbSnapshot] = None) -> list[tuple[str, str]]:
    """The proposal table, in display order. Same content for plain and HTML."""
    side = _side(signal)
    tp_formula = "entry + delta" if side == "BUY" else "entry − delta"
    sl_formula = "entry − delta" if side == "BUY" else "entry + delta"
    minutes = signal.candle_minutes or config.CONFIRM_CANDLE_MINUTES

    candle = f"{_et(signal.confirm_open, '%H:%M')}–{_et(signal.confirm_close, '%H:%M')} ET, {minutes}-min"
    conf = snapshot.confirmation if snapshot is not None else None
    if conf is not None:
        candle += f", O {conf.open:.2f} H {conf.high:.2f} L {conf.low:.2f} C {conf.close:.2f}"

    return [
        ("Side", side),
        ("Entry (confirmation close)", _fmt(_entry(signal))),
        (f"Take profit ({tp_formula})", _fmt(signal.take_profit)),
        (f"Stop loss ({sl_formula})", _fmt(signal.stop_loss)),
        ("Range delta", _fmt(signal.delta)),
        ("Risk / reward", "1 : 1"),
        ("Confirmation candle", candle),
        ("Box top / bottom", f"{_fmt(signal.box_top)} / {_fmt(signal.box_bottom)}"),
        ("Time sent (ET)", _et(signal.fired_at, "%Y-%m-%d %H:%M:%S %Z")),
    ]


def build_plain(signal: Signal, snapshot: Optional[OrbSnapshot] = None) -> str:
    rows = build_rows(signal, snapshot)
    width = max(len(label) for label, _ in rows) + 1
    lines = [
        f"{_SIDE_ARROW[_side(signal)]} {signal.market} {_side(signal)} @ {_fmt(_entry(signal))}",
        f"{signal.strategy} — MarketScanner",
        "",
    ]
    lines += [f"{label + ':':<{width}} {value}" for label, value in rows]
    lines += ["", "Generated by MarketScanner — Opening Range Breakout strategy.",
              "Informational only — not an order."]
    return "\n".join(lines)


def build_html(signal: Signal, snapshot: Optional[OrbSnapshot] = None, has_chart: bool = False) -> str:
    side = _side(signal)
    colour = _SIDE_COLOUR[side]
    arrow = _SIDE_ARROW[side]

    table_rows = "".join(
        f"<tr>"
        f'<td style="padding:4px 12px 4px 0;color:#6b7280;white-space:nowrap">{label}</td>'
        f'<td style="padding:4px 0;font-weight:600">{value}</td>'
        f"</tr>"
        for label, value in build_rows(signal, snapshot)
    )

    chart_block = (
        '<p style="margin:20px 0 0">'
        '<img src="cid:chart" alt="chart" style="max-width:100%;border-radius:6px">'
        "</p>"
        if has_chart else ""
    )

    return f"""<!DOCTYPE html>
<html>
<body style="margin:0;padding:0;background:#f3f4f6;font-family:Arial,sans-serif">
<table width="100%" cellpadding="0" cellspacing="0" bgcolor="#f3f4f6">
  <tr><td align="center" style="padding:32px 16px">
    <table width="560" cellpadding="0" cellspacing="0"
           style="background:#ffffff;border-radius:8px;overflow:hidden;
                  box-shadow:0 1px 4px rgba(0,0,0,.12)">
      <!-- header -->
      <tr>
        <td style="background:{colour};padding:20px 24px">
          <span style="font-size:22px;font-weight:700;color:#fff">
            {arrow} {signal.market} {side} @ {_fmt(_entry(signal))}
          </span><br>
          <span style="font-size:13px;color:rgba(255,255,255,.85)">
            {signal.strategy} &mdash; MarketScanner
          </span>
        </td>
      </tr>
      <!-- body -->
      <tr>
        <td style="padding:24px">
          <table cellpadding="0" cellspacing="0" style="font-size:15px;color:#111">
            {table_rows}
          </table>
          {chart_block}
        </td>
      </tr>
      <!-- footer -->
      <tr>
        <td style="padding:12px 24px;background:#f9fafb;
                   font-size:11px;color:#9ca3af;border-top:1px solid #e5e7eb">
          Generated by MarketScanner &mdash; Opening Range Breakout strategy.<br>
          Informational only &mdash; not an order.
        </td>
      </tr>
    </table>
  </td></tr>
</table>
</body>
</html>"""


def build_message(
    signal: Signal,
    snapshot: Optional[OrbSnapshot] = None,
    chart_figure=None,
    sender: str = "",
    recipient: str = "",
) -> MIMEMultipart:
    """Assemble the MIME message (plain + HTML alternative, inline chart)."""
    chart_bytes: bytes | None = None
    if chart_figure is not None:
        buf = io.BytesIO()
        chart_figure.savefig(buf, format="png", bbox_inches="tight")
        chart_bytes = buf.getvalue()

    # Outer envelope: mixed (allows plain-attachment fallback for old clients)
    msg = MIMEMultipart("mixed")
    msg["Subject"] = build_subject(signal)
    msg["From"] = sender
    msg["To"] = recipient

    # related wraps html + inline image so cid: references resolve
    related = MIMEMultipart("related")

    # alternative: plain first, html last (clients pick the richest they support)
    alternative = MIMEMultipart("alternative")
    alternative.attach(MIMEText(build_plain(signal, snapshot), "plain", "utf-8"))
    alternative.attach(MIMEText(build_html(signal, snapshot, chart_bytes is not None), "html", "utf-8"))
    related.attach(alternative)

    if chart_bytes is not None:
        cid_img = MIMEImage(chart_bytes, name="chart.png")
        cid_img.add_header("Content-ID", "<chart>")
        cid_img.add_header("Content-Disposition", "inline", filename="chart.png")
        related.attach(cid_img)

    msg.attach(related)
    return msg


def send_alert(signal: Signal, snapshot: Optional[OrbSnapshot] = None, chart_figure=None) -> None:
    subject = build_subject(signal)

    cfg = config.EMAIL
    if not cfg["sender"] or not cfg["password"] or not cfg["recipient"]:
        log.warning("Email not configured — signal logged but not sent: %s", signal)
        return

    msg = build_message(signal, snapshot, chart_figure, sender=cfg["sender"], recipient=cfg["recipient"])

    try:
        with smtplib.SMTP(cfg["smtp_host"], cfg["smtp_port"]) as smtp:
            smtp.ehlo()
            smtp.starttls()
            smtp.login(cfg["sender"], cfg["password"])
            smtp.sendmail(cfg["sender"], cfg["recipient"], msg.as_string())
        log.info("Alert sent: %s", subject)
    except Exception as exc:
        log.error("Failed to send alert: %s", exc)
